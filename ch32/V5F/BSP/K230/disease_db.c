#define DB_SIZE (sizeof(g_disease_db) / sizeof(g_disease_db[0]))

/* ==================== 公开接口 ==================== */

/**
 * @brief  根据病害名称查找知识库条目（strstr 子串匹配）
 *         匹配顺序为数组顺序，先匹配到先返回。
 *         "虫害" 作为通用兜底放在具体虫害之后，避免过早匹配。
 */
const DiseaseEntry* DiseaseDB_Find(const char* pest_name)
{
    if (!pest_name || pest_name[0] == '\0' || pest_name[0] == '-')
        return NULL;  /* 无效输入，由调用方处理 */

    for (uint8_t i = 0; i < DB_SIZE; i++) {
        if (strstr(pest_name, g_disease_db[i].keyword))
            return &g_disease_db[i];
    }
    return NULL;
}

uint8_t DiseaseDB_GetCount(void)
{
    return DB_SIZE;
}
